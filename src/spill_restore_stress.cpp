// Claim: "restoring 100,000 spilled blocks bit-identically".
//
// Spills >=100,000 KV-cache-block-sized buffers through
// compress -> write (NVMe) -> read -> decompress and checks every single
// one reproduces the exact original bytes. Pure host-side (no GPU needed):
// it exercises block_storage.hpp's zlib_compress/zlib_decompress and
// NvmeBlockStore directly, the same primitives TieredKVBlockManager uses
// for its DRAM/NVMe tiers (already round-tripped through real device
// memory at small scale in tests/tiered_kv_test.cpp -- this test's job is
// scale, not novelty).
//
// Memory footprint: 100,000 blocks at the repo's real KV-cache block size
// (kNLayers*2*page_size*n_heads*head_dim*4 bytes, ~128 KiB) would be
// ~12.8 GB of raw bytes if all held in memory simultaneously -- more than
// the 12 GB this machine's WSL is capped to (see CLAUDE.md/BUILDER.md
// section 3z). Each block's "original" bytes are instead generated by a
// block-index-seeded deterministic PRNG, so they're regenerated (not
// retained) whenever needed for comparison; only a per-block NVMe
// (offset,length) locator and a 64-bit checksum stay resident across all
// 100,000 blocks (a few MB total), not the blocks themselves.
#include <cstdio>
#include <cstdlib>
#include <cstdint>
#include <cstring>
#include <chrono>
#include <random>
#include <string>
#include <vector>
#include "config.hpp"
#include "block_storage.hpp"

using Clock = std::chrono::steady_clock;

namespace {

size_t block_bytes() {
  return (size_t)cfg::kNLayers * 2 * cfg::kPageSize * cfg::kNHeads * cfg::kHeadDim * sizeof(float);
}

// Deterministic per-block content, reproducible from block_index alone.
// Std-normal-ish floats (loosely modeling real activation magnitude)
// rather than adversarial wide-range noise -- see README for why generic
// lossless compression's ratio on float32 K/V bytes is modest either way
// (mantissas essentially never repeat, whatever the value range).
void generate_block(uint32_t block_index, std::vector<float>& out) {
  std::mt19937 rng(block_index * 2654435761u + 1u);
  std::normal_distribution<float> dist(0.f, 1.0f);
  for (auto& v : out) v = dist(rng);
}

uint64_t fnv1a(const uint8_t* data, size_t len) {
  uint64_t h = 1469598103934665603ull;
  for (size_t i = 0; i < len; ++i) {
    h ^= data[i];
    h *= 1099511628211ull;
  }
  return h;
}

}  // namespace

int main(int argc, char** argv) {
  int n_blocks = argc > 1 ? std::atoi(argv[1]) : 100000;
  std::string nvme_path = argc > 2 ? argv[2] : "spill_restore_stress.nvme";

  size_t bblen = block_bytes();
  size_t elems = bblen / sizeof(float);

  printf("spill_restore_stress: %d blocks, %zu bytes/block (%.1f KiB), nvme scratch file %s\n",
         n_blocks, bblen, bblen / 1024.0, nvme_path.c_str());

  NvmeBlockStore store(nvme_path);
  std::vector<NvmeBlockStore::Loc> locs((size_t)n_blocks);
  std::vector<uint64_t> checksums((size_t)n_blocks);
  std::vector<float> buf(elems);

  auto t0 = Clock::now();
  size_t compressed_bytes_total = 0;
  for (int i = 0; i < n_blocks; ++i) {
    generate_block((uint32_t)i, buf);
    checksums[i] = fnv1a(reinterpret_cast<const uint8_t*>(buf.data()), bblen);
    std::vector<uint8_t> compressed = zlib_compress(buf.data(), bblen);
    locs[i] = store.write_block(compressed.data(), (uint32_t)compressed.size());
    compressed_bytes_total += compressed.size();
    if ((i + 1) % 10000 == 0) { printf("  spilled %d/%d\n", i + 1, n_blocks); fflush(stdout); }
  }
  auto t1 = Clock::now();

  int mismatches = 0;
  std::vector<uint8_t> restored(bblen);
  for (int i = 0; i < n_blocks; ++i) {
    std::vector<uint8_t> compressed = store.read_block(locs[i]);
    zlib_decompress(compressed.data(), compressed.size(), restored.data(), restored.size());

    generate_block((uint32_t)i, buf);  // regenerate the known original, don't retain it across the loop
    uint64_t restored_sum = fnv1a(restored.data(), bblen);
    bool ok = (restored_sum == checksums[i]) &&
              (std::memcmp(restored.data(), buf.data(), bblen) == 0);
    if (!ok) {
      mismatches++;
      if (mismatches <= 5) fprintf(stderr, "MISMATCH at block %d\n", i);
    }
    if ((i + 1) % 10000 == 0) { printf("  restored %d/%d\n", i + 1, n_blocks); fflush(stdout); }
  }
  auto t2 = Clock::now();

  double spill_s = std::chrono::duration<double>(t1 - t0).count();
  double restore_s = std::chrono::duration<double>(t2 - t1).count();
  double raw_total_gb = (double)n_blocks * bblen / 1e9;
  double compressed_total_gb = (double)compressed_bytes_total / 1e9;

  printf("\n== spill/restore stress summary ==\n");
  printf("  blocks                    : %d\n", n_blocks);
  printf("  block size                : %zu bytes\n", bblen);
  printf("  raw total                 : %.2f GB\n", raw_total_gb);
  printf("  compressed total (NVMe)   : %.2f GB (ratio %.3fx)\n", compressed_total_gb,
         raw_total_gb / compressed_total_gb);
  printf("  spill  (compress+write)   : %.1f s  (%.0f blocks/s)\n", spill_s, n_blocks / spill_s);
  printf("  restore (read+decompress) : %.1f s  (%.0f blocks/s)\n", restore_s, n_blocks / restore_s);
  printf("  mismatches                : %d / %d\n", mismatches, n_blocks);
  printf("%s\n", mismatches == 0 ? "SPILL/RESTORE STRESS PASSED (bit-identical)" : "SPILL/RESTORE STRESS FAILED");

  return mismatches == 0 ? 0 : 1;
}
